import CoreGraphics

/// Central spacing scale. Use these instead of literal point values so layout
/// rhythm stays consistent and adjustable from one place.
enum AppSpacing {
    static let s: CGFloat = 8
    static let m: CGFloat = 16
    static let l: CGFloat = 24
    static let xl: CGFloat = 32
}
